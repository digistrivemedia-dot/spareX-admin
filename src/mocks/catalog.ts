function buildFitment(fits: string[], productIndex: number): Fitment[] {
  return fits.flatMap((reference): Fitment[] => {
    const [modelName, fuel] = reference.split(":")
    const model = vehicleModels.find(
      (candidate) => `vm_${slugify(modelName ?? "")}` === candidate.id,
    )
    if (!model) throw new Error(`Unknown model in demo fitment: ${reference}`)
    if (!fuel)
      return [
        {
          id: `fit_${productIndex}_${model.id}`,
          brandId: model.brandId,
          modelId: model.id,
          variantId: null,
          years: [],
        },
      ]
    return vehicleVariants
      .filter((variant) => variant.modelId === model.id && variant.fuel === fuel)
      .map((variant) => ({
        id: `fit_${productIndex}_${variant.id}`,
        brandId: model.brandId,
        modelId: model.id,
        variantId: variant.id,
        years: variant.years,
      }))
  })
}

function buildProducts(): Product[] {
  const random = seededRandom(7)
  return PRODUCTS.map(([name, subcategory, brand, types, mrp, price, stock, fits], index) => {
    const subcategoryId = `cat_${slugify(subcategory)}`
    const categoryId =
      productCategories.find((category) => category.id === subcategoryId)?.parentId ?? subcategoryId
    const number = String(index + 1).padStart(3, "0")
    const createdAt = daysAgo(150 - index * 2)
    return {
      id: `prd_${number}`,
      name,
      slug: slugify(name),
      sku: `SPX-${slugify(subcategory).slice(0, 3).toUpperCase()}-${number}`,
      partNumber: `${slugify(brand).slice(0, 3).toUpperCase()}${random.int(10000, 99999)}`,
      hsnCode: HSN_BY_CATEGORY[categoryId] ?? "87089900",
      gstRate: GST_RATE_PERCENT,
      categoryId,
      subcategoryId,
      partBrandId: `pb_${slugify(brand)}`,
      vehicleTypes: types,
      description: `${name}. Genuine stock supplied by Kannali Garage with a GST invoice.`,
      specs: [
        { label: "Brand", value: brand },
        { label: "Type", value: subcategory },
      ],
      images: [],
      mrp: mrp * 100,
      price: price * 100,
      stock,
      lowStockLevel: 10,
      dimensionsMm: {
        length: random.int(80, 400),
        width: random.int(60, 300),
        height: random.int(30, 250),
      },
      weightGrams: random.int(80, 6000),
      warrantyMonths: subcategory.includes("batteries")
        ? 24
        : subcategory.includes("tyres")
          ? 12
          : 0,
      fitment: buildFitment(fits, index + 1),
      seoTitle: `${name} | SpareX`,
      seoDescription: `Buy ${name} online at the best price with fitment check and fast delivery.`,
      active: index !== 46,
      installationAvailable: false,
      installationCharge: null,
      createdAt,
      updatedAt: daysAgo(random.int(1, 40)),
    }
  })
}

